#!/usr/bin/env node
// Scope, tripwire, and test check for a pull request.
// Usage: node .harness/scripts/pr-scope-check.mjs [base=origin/main] [head=HEAD] [--strict] [--json] [--output-verdict <file>]
//   Hub (default): advisory. Prints problems and always exits 0.
//   Spoke (--strict): blocking. Exits 1 on any problem so the PR check shows red.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const ACTIVE_TASK = /^\s*-\s*\[.\].*\[IN_PROGRESS\]/;
const SLICE_TYPE = /\[(UI \/ VISUAL|CORE \/ DATA)\]/;
const DONE_SLICE = /^\s*-\s*\[x\]\s*\*\*Slice\b/i;
const TEST_FILE = /(\.test\.|\.spec\.)[^/]*$|(^|\/)test_[^/]*\.py$|_test\.(py|go)$/;
export const isCommentLine = (line) => /^\s*(?:\/\/|#|--|\*|\/\*)/.test(line);
export const ASSERTION = /expect\(|assert\(|assert\.|assert\s+|\.should|\.to\.be|\.toBe|\.toEqual|\.toMatch|\.toThrow|t\.(?:is|true|false|assert)\(|self\.assert|pytest\.raises|self\.assertRaises|t\.Error|t\.Fatal|require\.|assert!|assert_eq!|assert_ne!/;
// Anchored to the start of a line, so the text inside a string or fixture does not count
export const SKIP_MARK = /^\s*(?:(?:it|test|describe)\.(?:skip|only)\(|(?:xit|xdescribe)\(|test\.todo\(|@(?:pytest\.mark\.)?skip|@unittest\.skip|pytest\.skip\(|t\.(?:Skip|skip)\()/;
const MANIFEST = /(^|\/)(package\.json|package-lock\.json|pnpm-lock\.yaml|yarn\.lock|bun\.lockb?|requirements[^/]*\.txt|pyproject\.toml|uv\.lock|go\.(mod|sum)|Cargo\.(toml|lock))$/;
// Spoke-owned engine-adjacent files that a spoke may change even though they sit in an engine folder
const SPOKE_OWNED = new Set(['.claude/project-rules.md', '.claude/settings.spoke.json']);
// Harness files a spoke receives from the hub: the slice gate workflows (copied from templates) and the gate script.
// A spoke PR that carries exactly these paths is not a tripwire. Their content is not checked against the hub here,
// so the PR check cannot prove they match the hub; the Referee watch on main is the backstop for that.
export const SYNC_DELIVERED = new Set([
  '.github/workflows/harness-slice-gate.yml',
  '.github/workflows/harness-referee-watch.yml',
  '.harness/scripts/ci-gate.mjs',
  '.harness/scripts/ci-gate.test.mjs',
]);

export function isPackageJsonVersionOnly(fileDiff) {
  if (!fileDiff) return false;
  const { added = [], removed = [] } = fileDiff;
  if (added.length === 0 && removed.length === 0) return false;
  const VERSION_LINE = /^\s*"version"\s*:\s*"[^"]+"\s*,?\s*$/;
  return added.every((l) => VERSION_LINE.test(l)) && removed.every((l) => VERSION_LINE.test(l));
}

// Supabase migrations are a Red tripwire, except a new or additive-only SQL file under supabase/migrations/.
// An edit that removes lines from an existing migration still trips the wire. Charlie approved this exemption
// for the Concert Tracker spoke (2026-11-04); other paths under migrations folders still trip.
export function isAdditiveSupabaseMigration(file, diff) {
  if (!/^supabase\/migrations\/[^/]+\.sql$/.test(file)) return false;
  const fileDiff = diff && diff.get ? diff.get(file) : null;
  if (!fileDiff) return false;
  return (fileDiff.removed || []).length === 0;
}

// Red tripwires: any match makes the slice Red, whatever colour the slice line carries
export const TRIPWIRES = [
  {
    name: 'dependency manifest or lockfile',
    test: (f, diff) => {
      if (!MANIFEST.test(f)) return false;
      if ((f === 'package.json' || f.endsWith('/package.json')) && diff && diff.has(f)) {
        if (isPackageJsonVersionOnly(diff.get(f))) return false;
      }
      return true;
    },
  },
  {
    name: 'migrations folder',
    test: (f, diff) => /(^|\/)migrations\//.test(f) && !isAdditiveSupabaseMigration(f, diff),
  },
  { name: 'schema file', test: (f) => /schema/i.test(f) },
  { name: 'auth file', test: (f) => /(^|[/._-])auth([/._-]|$)/i.test(f) },
  { name: 'env file', test: (f) => /(^|\/)\.env[^/]*$/.test(f) },
  { name: 'AGENTS.md', test: (f) => f === 'AGENTS.md' },
  { name: 'CI workflow', test: (f) => f.startsWith('.github/workflows/') && !SYNC_DELIVERED.has(f) },
];

export const isTestFile = (file) => TEST_FILE.test(file);
export const isEngineFile = (file) =>
  !SPOKE_OWNED.has(file) && !SYNC_DELIVERED.has(file)
  && (file.startsWith('.claude/') || file.startsWith('.harness/') || file === '.harness-version');

// A hub sync is the only legitimate way for a spoke to change engine files. It rewrites each synced file and
// records its sha256 in .harness/managed.json. True only when every engine file changed matches its recorded hash,
// managed.json itself changed, and nothing engine-owned was deleted.
export const MANAGED = '.harness/managed.json';
// settings.json is generated by merging hub settings with the spoke extras. Its permissions block must equal the
// generated permissions recorded in managed.json (settingsGenerated). Other keys are not verified here.
export const SETTINGS = '.claude/settings.json';
export function isHubSync({ changed, deleted = [], managed, hashOf, settingsMatches = false }) {
  const engine = changed.filter(isEngineFile);
  if (engine.length === 0 || deleted.some(isEngineFile)) return false;
  if (!changed.includes(MANAGED) || !managed || typeof managed.files !== 'object') return false;
  return engine.every((file) => {
    if (file === MANAGED) return true;
    if (file === SETTINGS) return settingsMatches;
    return managed.files[file] !== undefined && managed.files[file] === hashOf(file);
  });
}

// AGENTS.md's harness block is written by hub-sync. Outside that block the file must match the base exactly.
const AGENTS_START = '<!-- >>> harness >>> -->';
const AGENTS_END = '<!-- <<< harness <<< -->';
export function outsideHarnessBlock(text) {
  if (text == null) return null;
  const start = text.indexOf(AGENTS_START);
  const end = text.indexOf(AGENTS_END);
  if (start === -1 || end === -1 || end < start) return text;
  return text.slice(0, start) + text.slice(end + AGENTS_END.length);
}

export function parseActiveTargets(line) {
  if (!line) return [];
  const targetPart = line.split('|')[0];
  const match = targetPart.match(/Target files:\s*([^\n]+)/i);
  if (!match) return [];
  return match[1]
    .replace(/\[NEW\]/gi, '')
    .replace(/\[IN_PROGRESS\]/gi, '')
    .replace(/\[DELETE\]/gi, '')
    .replace(/[`*]/g, '')
    .split(',')
    .map((s) => s.trim().replace(/^\.\//, ''))
    .filter(Boolean);
}

// `git diff --name-status -M` output -> changed paths and deleted paths (a rename deletes its old path)
export function parseNameStatus(text) {
  const changed = [];
  const deleted = [];
  for (const line of text.split('\n').filter(Boolean)) {
    const [status, ...paths] = line.split('\t');
    const letter = status[0];
    if (letter === 'D') deleted.push(paths[0]);
    else if (letter === 'R') { deleted.push(paths[0]); changed.push(paths[1]); }
    else changed.push(paths[paths.length - 1]);
  }
  return { changed: [...new Set(changed)], deleted };
}

// `git diff -U0` output -> per-file lists of added and removed content lines
export function parseDiff(text) {
  const files = new Map();
  let current = null;
  let inHunk = false;
  for (const line of text.split('\n')) {
    if (line.startsWith('diff --git ')) { current = null; inHunk = false; continue; }
    if (!inHunk && line.startsWith('+++ ')) {
      const name = line.slice(4).replace(/^b\//, '');
      current = name === '/dev/null' ? null : name;
      if (current && !files.has(current)) files.set(current, { added: [], removed: [] });
      continue;
    }
    if (line.startsWith('@@')) { inHunk = true; continue; }
    if (!inHunk || !current) continue;
    if (line.startsWith('+')) files.get(current).added.push(line.slice(1));
    else if (line.startsWith('-')) files.get(current).removed.push(line.slice(1));
  }
  return files;
}

// Pure check. Inputs come from git (see main) or from tests.
export function analyze({
  changed,
  deleted = [],
  diff = new Map(),
  progress = '',
  strict = false,
  root = process.env.CLAUDE_PROJECT_DIR || process.cwd(),
  thresholds = null,
  fileContents = null,
  hubSync = false,
  agentsBlockOnly = false,
}) {
  const problems = [];
  const notes = [];
  let tripwireFired = false;

  // A deletion-only PR still changed files, so count deletions as touched
  const touched = [...new Set([...changed, ...deleted])];
  if (touched.length === 0) problems.push('The diff is empty. There is nothing to review.');

  for (const file of changed) {
    if (agentsBlockOnly && file === 'AGENTS.md') continue;
    for (const t of TRIPWIRES) {
      if (t.test(file, diff)) { problems.push(`Red tripwire (${t.name}): ${file}`); tripwireFired = true; }
    }
  }
  for (const file of deleted) { problems.push(`Red tripwire (file deleted): ${file}`); tripwireFired = true; }

  if (hubSync && touched.some(isEngineFile)) {
    notes.push('Hub sync: every engine file change matches its hash in .harness/managed.json.');
  } else {
    for (const file of touched) {
      if (!isEngineFile(file)) continue;
      if (strict) problems.push(`Spoke changed an engine file, which the hub owns: ${file}`);
      else notes.push(`Engine file changed: ${file}. Confirm this is intended.`);
    }
  }

  for (const file of touched) {
    if (SYNC_DELIVERED.has(file)) notes.push(`Sync-delivered harness file: ${file}. Allowed by the scope check; its content is not verified against the hub.`);
  }

  // Scope rule: while exactly one slice is [IN_PROGRESS], only its Target files (and .spec/) may change.
  // A slice PR usually marks its slice [x] by the time it opens, so fall back to slice lines this PR marks done.
  const active = progress.split('\n').filter((l) => ACTIVE_TASK.test(l));
  const doneInPr = (diff.get('.spec/PROGRESS.md')?.added ?? []).filter((l) => DONE_SLICE.test(l));
  // A finish-slice commit promotes the next pending slice to [IN_PROGRESS]. When this PR changes none of that
  // slice's Target files, the marker is only the next slice's placeholder, so the PR's done slices are checked.
  const activeTargetsTouched = (line) => parseActiveTargets(line).some((t) =>
    changed.some((file) => file === t || file.startsWith(t.endsWith('/') ? t : `${t}/`)));
  let sliceLines = [];
  if (active.length > 1) {
    problems.push(`${active.length} slices are [IN_PROGRESS]. The harness allows only one.`);
  } else if (active.length === 1 && (doneInPr.length === 0 || activeTargetsTouched(active[0]))) {
    sliceLines = active;
  } else if (doneInPr.length > 0) {
    sliceLines = doneInPr;
    notes.push(active.length === 1
      ? `The [IN_PROGRESS] slice has no changed Target files in this PR. Checking the ${doneInPr.length} slice(s) this PR marks done.`
      : `No slice is [IN_PROGRESS]. Checking the ${doneInPr.length} slice(s) this PR marks done.`);
  } else if (active.length === 1) {
    sliceLines = active;
  }

  let sliceType = null;
  if (sliceLines.length > 0) {
    sliceType = sliceLines.some((l) => l.match(SLICE_TYPE)?.[1] === 'CORE / DATA') ? 'CORE / DATA'
      : sliceLines.map((l) => l.match(SLICE_TYPE)?.[1]).find(Boolean) ?? null;
    const targets = sliceLines.flatMap((l) => parseActiveTargets(l));
    // Same rule as the guard hook: exact file, or a file inside a listed folder
    const isAllowed = (file, allowed) =>
      file === allowed || file.startsWith(allowed.endsWith('/') ? allowed : `${allowed}/`);
    for (const file of touched) {
      if (
        file.startsWith('.spec/') ||
        file === 'CLAUDE.md' ||
        // A verified hub sync changes only hub-owned engine files and their manifest; the hash check above covers them
        (hubSync && (isEngineFile(file) || file === MANAGED || file === SETTINGS)) ||
        ((file === 'package.json' || file.endsWith('/package.json')) && isPackageJsonVersionOnly(diff.get(file))) ||
        targets.some((t) => isAllowed(file, t))
      ) continue;
      if (targets.some((t) => t.includes('el-exit-gate') || t.includes('pre-tool-guard')) && file === '.harness/hooks/lib/guard-rules.test.mjs') continue;
      if (targets.some((t) => t.startsWith('.harness/agents/')) &&
          (file.startsWith('.claude/agents/') || (file.startsWith('.agents/') && !file.startsWith('.agents/rules/') && !file.startsWith('.agents/skills/')))) continue;
      problems.push(`Outside the slice's Target files: ${file}`);
    }
  } else if (active.length === 0) {
    notes.push('Vibe Mode: no slice is in progress, so the Target files rule does not apply.');
  }

  // Verify line budgets against thresholds.json if present
  let resolvedThresholds = thresholds;
  if (!resolvedThresholds && root) {
    const configPath = path.join(root, '.harness', 'config', 'thresholds.json');
    if (fs.existsSync(configPath)) {
      try {
        resolvedThresholds = JSON.parse(fs.readFileSync(configPath, 'utf8'));
      } catch {}
    }
  }

  const softCaps = resolvedThresholds?.line_budgets?.soft_caps;
  if (softCaps && typeof softCaps === 'object') {
    for (const [budgetFile, maxLines] of Object.entries(softCaps)) {
      if (touched.includes(budgetFile) && !(agentsBlockOnly && budgetFile === 'AGENTS.md')) {
        let content = null;
        if (fileContents && fileContents.has && fileContents.has(budgetFile)) {
          content = fileContents.get(budgetFile);
        } else if (fileContents && budgetFile in fileContents) {
          content = fileContents[budgetFile];
        } else if (root) {
          const filePath = path.join(root, budgetFile);
          if (fs.existsSync(filePath)) {
            try { content = fs.readFileSync(filePath, 'utf8'); } catch {}
          }
        }
        if (content !== null) {
          const lines = content.endsWith('\n') ? content.slice(0, -1).split('\n').length : content.split('\n').length;
          if (lines > maxLines) {
            problems.push(`Line budget exceeded: ${budgetFile} has ${lines} lines (soft cap: ${maxLines})`);
          }
        }
      }
    }
  }

  // Test rule. Tests must not lose assertions, and skipped or focused tests are flagged.
  let addedAsserts = 0;
  let removedAsserts = 0;
  for (const [file, lines] of diff) {
    if (!isTestFile(file)) continue;
    for (const line of lines.added) {
      if (isCommentLine(line)) continue;
      if (ASSERTION.test(line)) addedAsserts++;
      if (SKIP_MARK.test(line)) problems.push(`Test skipped or focused in ${file}: ${line.trim()}`);
    }
    for (const line of lines.removed) {
      if (isCommentLine(line)) continue;
      if (ASSERTION.test(line)) removedAsserts++;
    }
  }
  if (removedAsserts > addedAsserts) {
    problems.push(`Yellow: ${removedAsserts - addedAsserts} assertion line(s) removed from tests with no replacement.`);
  }
  if (sliceType === 'CORE / DATA') {
    const testChanged = changed.some(isTestFile);
    if (!testChanged) {
      problems.push('CORE / DATA slice needs a test file change (*.test.*, *.spec.*, test_*.py, *_test.py, *_test.go). None changed.');
    } else if (addedAsserts === 0) {
      problems.push('CORE / DATA slice: test files changed but no assertion line was added or modified.');
    }
  }

  return { problems, notes, tripwireFired, sliceType };
}

export function report({ changed, problems, notes, tripwireFired, strict }) {
  const lines = [
    `Mode: ${strict ? 'strict (spoke, blocking)' : 'advisory (hub, never blocks)'}`,
    `Changed files: ${changed.length}`,
  ];
  if (problems.length === 0) lines.push('PR SCOPE: CLEAN');
  else lines.push('PR SCOPE: PROBLEMS', ...problems.map((p) => `- ${p}`));
  if (tripwireFired) lines.push('A Red tripwire fired, so this slice counts as Red. Stop and get a decision before merging.');
  if (notes.length) lines.push('Notes:', ...notes.map((n) => `- ${n}`));
  return lines.join('\n');
}

export function formatJsonVerdict({
  changed = [],
  deleted = [],
  diff = new Map(),
  progress = '',
  strict = false,
  base = 'origin/main',
  head = 'HEAD',
  problems = [],
  notes = [],
  tripwireFired = false,
  sliceType = null,
} = {}) {
  return {
    schemaVersion: "1.0.0",
    timestamp: new Date().toISOString(),
    verdict: problems.length === 0 ? "CLEAN" : "NEEDS_CHANGES",
    mode: strict ? "strict" : "advisory",
    target: { base, head },
    summary: {
      changedFiles: changed.length,
      deletedFiles: deleted.length,
      problemCount: problems.length,
      tripwireFired,
      noteCount: notes.length,
    },
    sliceType,
    findings: problems.map((msg, i) => {
      let type = "other";
      if (msg.startsWith("Red tripwire")) type = "tripwire";
      else if (msg.includes("Target files") || msg.includes("IN_PROGRESS")) type = "scope";
      else if (msg.toLowerCase().includes("test") || msg.toLowerCase().includes("assertion")) type = "test";
      else if (msg.includes("engine file")) type = "engine";
      else if (msg.includes("Line budget")) type = "budget";
      return {
        id: `REV-${String(i + 1).padStart(3, '0')}`,
        type,
        severity: tripwireFired || strict ? "error" : "warning",
        message: msg,
        status: "open",
      };
    }),
    notes,
  };
}

function main(argv) {
  const strict = argv.includes('--strict');
  const jsonOutput = argv.includes('--json');
  let outputVerdictFile = null;
  const positionals = [];

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--strict' || arg === '--json') {
      continue;
    } else if (arg === '--output-verdict') {
      outputVerdictFile = argv[++i];
    } else if (arg.startsWith('--output-verdict=')) {
      outputVerdictFile = arg.slice('--output-verdict='.length);
    } else if (!arg.startsWith('--')) {
      positionals.push(arg);
    }
  }

  const [base = 'origin/main', head = 'HEAD'] = positionals;
  const root = process.env.CLAUDE_PROJECT_DIR || process.cwd();
  const git = (...args) => execFileSync('git', args, {
    cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024,
  });

  let nameStatus;
  let diffText;
  try {
    nameStatus = git('diff', '--name-status', '-M', `${base}...${head}`);
    diffText = git('diff', '--no-color', '--no-ext-diff', '--src-prefix=a/', '--dst-prefix=b/', '-U0', `${base}...${head}`);
  } catch (err) {
    console.log(`PR SCOPE: ERROR. Could not diff ${base}...${head}: ${String(err.stderr || err.message).trim().split('\n')[0]}`);
    process.exit(strict ? 1 : 0);
  }

  let progress = '';
  try { progress = git('show', `${head}:.spec/PROGRESS.md`); } catch { /* no PROGRESS file: Vibe Mode */ }

  const { changed, deleted } = parseNameStatus(nameStatus);
  const diff = parseDiff(diffText);
  // Hashes are read from the checked-out head, which is what CI is verifying.
  let managed = null;
  try { managed = JSON.parse(fs.readFileSync(path.join(root, MANAGED), 'utf8')); } catch { /* no manifest: not a sync */ }
  const hashOf = (file) => {
    try { return crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex'); }
    catch { return null; }
  };
  let settingsMatches = false;
  try {
    const perms = JSON.parse(fs.readFileSync(path.join(root, SETTINGS), 'utf8')).permissions ?? {};
    settingsMatches = managed?.settingsGenerated != null
      && JSON.stringify(perms) === JSON.stringify(managed.settingsGenerated);
  } catch { /* no settings file: not verified */ }
  const hubSync = strict && isHubSync({ changed, deleted, managed, hashOf, settingsMatches });
  // The AGENTS.md exemption applies only when the sync's own check passed and the rest of the file is unchanged
  let agentsBlockOnly = false;
  if (hubSync && changed.includes('AGENTS.md')) {
    let baseText = null;
    try { baseText = git('show', `${base}:AGENTS.md`); } catch { /* new file: not verified */ }
    let headText = null;
    try { headText = fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8'); } catch { /* missing: not verified */ }
    agentsBlockOnly = baseText !== null && headText !== null
      && outsideHarnessBlock(baseText) === outsideHarnessBlock(headText);
  }
  const result = analyze({ changed, deleted, diff, progress, strict, root, hubSync, agentsBlockOnly });

  const verdict = formatJsonVerdict({
    changed,
    deleted,
    diff,
    progress,
    strict,
    base,
    head,
    ...result,
  });

  if (outputVerdictFile) {
    const targetPath = path.isAbsolute(outputVerdictFile)
      ? outputVerdictFile
      : path.resolve(root, outputVerdictFile);
    fs.mkdirSync(path.dirname(targetPath), { recursive: true });
    fs.writeFileSync(targetPath, JSON.stringify(verdict, null, 2) + '\n', 'utf8');
  }

  if (jsonOutput) {
    console.log(JSON.stringify(verdict, null, 2));
  } else {
    console.log(report({ changed, strict, ...result }));
  }

  process.exit(strict && result.problems.length > 0 ? 1 : 0);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
